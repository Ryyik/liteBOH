/**
 * BOH AI 跨场景共用的提示词规则 —— 单一真源
 * ------------------------------------------------------------
 * 背景（plans/024 §1.5 ②）：「不编造」这一条规则曾在 **12 个**提示块里各写一份，
 * 措辞各异（「绝对不能编造事实」/「不要推算、不要编造」/「绝对不能编造帖子内容…」），
 * 改一次口径要动 12 处，而且无法审计「到底哪几处在管这件事」。
 * 2026-09-24 的审查记录里是 9 份 —— 两个月长到 12 份，说明「加规则」是默认动作。
 *
 * 这里把**跨场景同义**的那几句收口成常量；带场景专有范围的措辞留在原处
 * （例如论坛专用的「不要编造论坛用户、帖子或链接」、健康专用的「不要推算」、
 * plan 模式专用的「不要编造进度/路径/字段」）—— 它们的范围限定本身就是信息，
 * 换成通用句反而更弱。
 *
 * 维护约定：
 * 1. 新增「不编造 / 不提技术词 / 不吐 JSON」类规则时，**先引用这里的常量**；
 *    只有在需要额外范围限定时，才在常量之后追加自己的那一行。
 * 2. 改这里的措辞 = 同时改所有引用点。改前想清楚。
 * 3. 与 `generation-params.js` 的分工：那个是**参数**真源，这个是**规则**真源。
 * ------------------------------------------------------------
 */

/** 「不编造」的通用表述。缺依据时该做什么，而不是只说不许做什么。 */
export const NO_FABRICATION_RULE =
  '- 只基于已给出的资料作答；没有依据的部分直接说「不确定」，不要凭印象补全。';

/** 「不暴露内部实现」——覆盖 Agent 名 / 模型名 / prompt 等技术词。 */
export const NO_TECH_TERMS_RULE = '- 不暴露内部 Agent 名称、模型名、prompt 等技术词。';

/** 「不吐结构化垃圾」——用户没要就不给 JSON / 代码块。 */
export const NO_RAW_JSON_RULE = '- 除用户明确要求，不输出 JSON 或代码块。';
