/**
 * 「壳已就绪」的判据 —— 单一真源（App.vue 的启动态唯一使用者）。
 *
 * ── 为什么需要它（2026-10-27）──────────────────────────────────────────
 * 启动态原本只靠 `router.isReady().then(...)` 置位。问题在于 `isReady()` 是
 * **一次性**的：它描述的是「首次导航确认」，一旦首次导航被 reject（部署窗口期
 * 旧 hash chunk 404 是最常见的原因），这个 promise 永远不会再 resolve。
 * 之后用户再导航成功、路由内容其实已经渲染出来了，那块 60vh 的启动态仍然挂着，
 * 只能死等 10s 超时切到报错态 —— 用户看到的就是截图里那副样子：
 * 上面「正在加载…」，下面内容已经把两块面板的失败态都画出来了。
 *
 * 所以补一条 `router.afterEach` 兜底：任何一次**成功**的导航都算「壳已就绪」。
 *
 * ⚠️ 判 `failure` 不是保险起见，是必须：vue-router 4 的 afterEach 在导航
 *   **被取消 / 抛错**时同样会调用（第三参为非空 failure）。不判的话，「导航失败」
 *   会被误判成「就绪」—— 启动态提前撤掉，露出半截页面，比一直转圈更难解释。
 */
export const shouldMarkBootReady = (failure, bootReady) => !failure && !bootReady;
